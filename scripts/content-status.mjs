#!/usr/bin/env node
/**
 * Readiness matrix: every entry group of every content type against every
 * locale, with publication state, remaining [TODO: …] placeholders, word count
 * and reading time.
 *
 * Usage:
 *   pnpm run content:status [--json] [--write=docs/STATUS.md] [--type=<type>]
 *
 * `--write` produces a Markdown report suitable for a client hand-off.
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  KNOWN_TYPES,
  contentDirFor,
  contentTypeKeyError,
  countTodos,
  countWords,
  groupDirs,
  readContentTypes,
  rootDir,
} from './lib/content-types.mjs';
import { readLocaleConfig } from './lib/locales.mjs';
import { parseFrontmatter } from './lib/frontmatter.mjs';

const args = process.argv.slice(2);
const wantsJson = args.includes('--json');
const writeArg = args.find((arg) => arg.startsWith('--write='));
const typeArg = args.find((arg) => arg.startsWith('--type='));

const typeFilter = typeArg ? typeArg.slice(7) : '';
if (typeFilter) {
  const error = contentTypeKeyError(typeFilter);
  if (error) {
    console.error(error);
    process.exit(1);
  }
}

const { locales, defaultLocale } = readLocaleConfig();
const WORDS_PER_MINUTE = 200;

function entryFile(groupDir, locale) {
  for (const extension of ['mdx', 'md']) {
    const candidate = path.join(groupDir, `${locale}.${extension}`);
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

const report = [];

for (const type of readContentTypes()) {
  if (!KNOWN_TYPES.includes(type.key)) continue;
  if (typeFilter && type.key !== typeFilter) continue;

  const dir = contentDirFor(type.key);
  const groups = groupDirs(type.key);

  for (const group of groups) {
    const groupDir = path.join(dir, group);
    const localesReport = {};

    for (const locale of locales) {
      const file = entryFile(groupDir, locale);
      if (!file) {
        localesReport[locale] = { state: 'missing' };
        continue;
      }
      const source = fs.readFileSync(file, 'utf-8');
      const { data, body } = parseFrontmatter(source);
      const words = countWords(body);
      localesReport[locale] = {
        state: data.draft === true ? 'draft' : 'published',
        title: String(data.title ?? ''),
        slug: String(data.slug ?? ''),
        words,
        readingMinutes: Math.max(1, Math.ceil(words / WORDS_PER_MINUTE)),
        todos: countTodos(source),
        modified: fs.statSync(file).mtime.toISOString().slice(0, 10),
      };
    }

    report.push({
      type: type.key,
      group,
      enabled: type.enabled,
      locales: localesReport,
    });
  }
}

const complete = report.filter((entry) =>
  locales.every((locale) => entry.locales[locale]?.state === 'published')
).length;

if (wantsJson) {
  console.log(JSON.stringify({ defaultLocale, locales, complete, total: report.length, entries: report }, null, 2));
  process.exit(0);
}

const symbol = { published: '✅', draft: '✏️ ', missing: '—' };
const localeWidth = Math.max(2, ...locales.map((locale) => locale.length));

function row(entry) {
  const cells = locales
    .map((locale) => {
      const value = entry.locales[locale];
      const mark = value ? symbol[value.state] : symbol.missing;
      return `${locale.padEnd(localeWidth)} ${mark}`;
    })
    .join('  ');
  const source = entry.locales[defaultLocale] ?? Object.values(entry.locales)[0];
  const words = source?.words ? `${source.words}w · ${source.readingMinutes}min` : '';
  const todos = Object.values(entry.locales).reduce(
    (sum, value) => sum + (value.todos ?? 0),
    0
  );
  const flags = [todos > 0 ? `${todos} TODO` : '', entry.enabled ? '' : 'type disabled']
    .filter(Boolean)
    .join(', ');
  return `  ${entry.type.padEnd(9)} ${entry.group.padEnd(26)} ${cells}  ${words.padEnd(13)} ${flags}`;
}

console.log('🗂️  Content readiness\n');
console.log(
  `  ${'type'.padEnd(9)} ${'group'.padEnd(26)} ${locales.map((locale) => locale.padEnd(localeWidth + 2)).join('  ')}  words         notes`
);
for (const entry of report) console.log(row(entry));

console.log(
  `\n${complete}/${report.length} group(s) fully published in all ${locales.length} locale(s).`
);
if (complete < report.length) {
  console.log('Draft/missing cells keep their locale out of the sitemap and the language switcher.');
}

if (writeArg) {
  const target = path.resolve(rootDir, writeArg.slice(8));
  const lines = [
    '# Content status',
    '',
    `Generated by \`pnpm run content:status\` on ${new Date().toISOString().slice(0, 10)}.`,
    '',
    `**${complete}/${report.length}** entry groups are published in every locale.`,
    '',
    `| Type | Group | ${locales.join(' | ')} | Words | Notes |`,
    `| --- | --- | ${locales.map(() => '---').join(' | ')} | --- | --- |`,
  ];

  for (const entry of report) {
    const cells = locales.map((locale) => {
      const value = entry.locales[locale];
      if (!value) return '—';
      return value.state === 'published' ? '✅' : value.state === 'draft' ? 'draft' : '—';
    });
    const source = entry.locales[defaultLocale] ?? Object.values(entry.locales)[0];
    const todos = Object.values(entry.locales).reduce((sum, value) => sum + (value.todos ?? 0), 0);
    const notes = [todos ? `${todos} TODO` : '', entry.enabled ? '' : 'type disabled']
      .filter(Boolean)
      .join(', ');
    lines.push(
      `| ${entry.type} | ${entry.group} | ${cells.join(' | ')} | ${source?.words ?? 0} | ${notes} |`
    );
  }

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${lines.join('\n')}\n`, 'utf-8');
  console.log(`\n📝 Wrote ${path.relative(rootDir, target)}`);
}
